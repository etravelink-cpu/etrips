def extract_region(title):
    """从标题中提取区域"""
    if not title:
        return ''
    for region, keywords in REGION_KEYWORDS.items():
        for kw in keywords:
            if kw in title:
                return region
    return ''

def fix_products():
    """修正产品数据"""
    json_path = os.path.join('data', 'products.json')
    
    if not os.path.exists(json_path):
        print(f'❌ 文件不存在: {json_path}')
        return
    
    # 读取数据
    with open(json_path, 'r', encoding='utf-8') as f:
        products = json.load(f)
    
    print(f'📊 共加载 {len(products)} 个产品')
    
    # 修正每个产品
    fixed_count = 0
    for p in products:
        name = p.get('name', '')
        old_region = p.get('region', '')
        
        # 如果区域为空或是国家名，从标题提取
        if not old_region or old_region in ['中国', '澳洲', '新西兰', '亚洲', '欧洲', '美加', '其他']:
            new_region = extract_region(name)
            if new_region:
                p['region'] = new_region
                fixed_count += 1
                print(f'   ✅ 修正: {p.get("id")} → "{new_region}" (原: "{old_region}")')
    
    # 保存
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(products, f, ensure_ascii=False, indent=2)
    
    print(f'\n✅ 修正完成！共修正 {fixed_count} 个产品的区域')

if __name__ == '__main__':
    fix_products()