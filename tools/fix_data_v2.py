def extract_region(title):
    """从标题中提取区域（增强版）"""
    if not title:
        return ''
    title = str(title)
    for region, keywords in REGION_KEYWORDS.items():
        for kw in keywords:
            if kw in title:
                return region
    return ''

def fix_products():
    """修正产品数据"""
    json_path = os.path.join('data', 'products.json')
    
    if not os.path.exists(json_path):
        print(f'❌ 文件不存在: {json_path}')
        return
    
    with open(json_path, 'r', encoding='utf-8') as f:
        products = json.load(f)
    
    print(f'📊 共加载 {len(products)} 个产品')
    
    # 统计需要修正的数量
    need_fix = []
    for p in products:
        region = p.get('region', '')
        # 如果区域是国家名或空，需要修正
        if not region or region in ['中国', '澳洲', '新西兰', '亚洲', '欧洲', '美加', '其他', '澳大利亚', 'USA', 'Canada']:
            need_fix.append(p)
    
    print(f'📌 需要修正的产品: {len(need_fix)} 个')
    
    fixed_count = 0
    for p in need_fix:
        name = p.get('name', '')
        old_region = p.get('region', '')
        new_region = extract_region(name)
        
        if new_region:
            p['region'] = new_region
            fixed_count += 1
            # 打印部分修正记录（只显示前30条）
            if fixed_count <= 30:
                print(f'   ✅ {p.get("id")}: "{old_region}" → "{new_region}"')
    
    # 保存
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(products, f, ensure_ascii=False, indent=2)
    
    print(f'\n✅ 修正完成！共修正 {fixed_count} 个产品的区域')
    print(f'📁 保存到: {json_path}')

if __name__ == '__main__':
    fix_products()